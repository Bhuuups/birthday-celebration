const express=require("express"),multer=require("multer"),fs=require("fs"),path=require("path"),crypto=require("crypto");
const D=process.env.DATA_DIR||path.join(__dirname,"data"),UP=path.join(D,"uploads"),DB=path.join(D,"db.json");
fs.mkdirSync(UP,{recursive:true});
const PASS=process.env.ADMIN_PASSWORD||"admin123";
let db={items:[],requests:[]};
try{db=JSON.parse(fs.readFileSync(DB))}catch(e){}
const save=()=>fs.writeFileSync(DB,JSON.stringify(db));
const rid=()=>crypto.randomBytes(5).toString("hex");
const S=(v,n)=>String(v||"").slice(0,n||200);
const up=multer({dest:UP,limits:{fileSize:8e6},fileFilter:(q,f,cb)=>cb(null,/^image\//.test(f.mimetype))});
const app=express(),tok=new Set();
app.use(express.json());
app.use("/uploads",express.static(UP));
app.use(express.static(path.join(__dirname,"public")));
const auth=(q,s,n)=>{const c=(q.headers.cookie||"").split(/;\s*/).find(x=>x.startsWith("adm="));c&&tok.has(c.slice(4))?n():s.status(401).json({error:"login karo"})};
app.post("/api/login",(q,s)=>{if(q.body.password!==PASS)return s.status(401).json({error:"Galat password"});
const t=crypto.randomBytes(16).toString("hex");tok.add(t);
s.setHeader("Set-Cookie","adm="+t+"; HttpOnly; Path=/; SameSite=Lax; Max-Age=604800");s.json({ok:1})});
app.get("/api/me",auth,(q,s)=>s.json({ok:1}));
app.get("/api/items",(q,s)=>s.json(db.items));
app.post("/api/items",auth,up.single("image"),(q,s)=>{const b=q.body;
if(!b.name)return s.status(400).json({error:"Naam zaroori hai"});
db.items.push({id:rid(),cat:S(b.cat,40),name:S(b.name,80),price:Math.max(0,+b.price||0),unit:b.unit==="guest"?"guest":"fixed",desc:S(b.desc,300),img:q.file?"/uploads/"+q.file.filename:""});
save();s.json({ok:1})});
app.delete("/api/items/:id",auth,(q,s)=>{const i=db.items.find(x=>x.id===q.params.id);
if(i&&i.img)fs.unlink(path.join(UP,path.basename(i.img)),()=>{});
db.items=db.items.filter(x=>x.id!==q.params.id);save();s.json({ok:1})});
app.post("/api/requests",(q,s)=>{const b=q.body;
if(!S(b.parent)||!/^\d{10,13}$/.test(S(b.phone).replace(/\D/g,"")))return s.status(400).json({error:"Naam aur sahi phone number likho"});
const g=Math.min(Math.max(+b.guests||1,1),1000),ids=Array.isArray(b.itemIds)?b.itemIds:[];
const items=db.items.filter(i=>ids.includes(i.id));
const total=items.reduce((t,i)=>t+(i.unit==="guest"?i.price*g:i.price),0);
db.requests.unshift({id:rid(),time:Date.now(),status:"new",student:S(b.student,80),parent:S(b.parent,80),phone:S(b.phone,15).replace(/\D/g,""),date:S(b.date,20),guests:g,budget:+b.budget||0,notes:S(b.notes,500),total,items:items.map(i=>({name:i.name,cat:i.cat,price:i.price,unit:i.unit}))});
save();s.json({ok:1})});
app.get("/api/requests",auth,(q,s)=>s.json(db.requests));
app.patch("/api/requests/:id",auth,(q,s)=>{const r=db.requests.find(x=>x.id===q.params.id);
if(r&&["new","contacted","confirmed","done"].includes(q.body.status)){r.status=q.body.status;save()}s.json({ok:1})});
app.listen(process.env.PORT||3000,()=>console.log("running"));
